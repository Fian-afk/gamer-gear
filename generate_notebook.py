    "def standardize_storage_to_gb(val):\n",
    "    if pd.isna(val):\n",
    "        return np.nan\n",
    "    val_str = str(val).strip()\n",
    "    match = re.search(r'(\\d+(?:\\.\\d+)?)\\s*(GB|TB)', val_str, re.IGNORECASE)\n",
    "    if match:\n",
    "        capacity = float(match.group(1))\n",
    "        unit = match.group(2).upper()\n",
    "        if unit == 'TB':\n",
    "            return int(capacity * 1024) # 1 TB = 1024 GB\n",
    "        elif unit == 'GB':\n",
    "            return int(capacity)\n",
    "    return np.nan\n",
